/**
 * Teste do codificador de QR Code próprio (CV2.DS4.US5).
 *
 * Um QR Code não pode ser conferido "no olho": a matriz parece certa mesmo
 * quando um campo inteiro está errado. Foi assim que o bug real desta história
 * passou despercebido — a informação de formato estava gravada TRANSPOSTA
 * (linha 8 no lugar da coluna 8), o desenho continuava com cara de QR e
 * nenhum leitor conseguia abrir.
 *
 * Por isso o teste compara a **matriz inteira, módulo a módulo**, com matrizes
 * de referência produzidas pela implementação de referência de Project Nayuki
 * (`qrcodegen`, a mesma usada como aferição pela maioria dos projetos de QR).
 * As matrizes abaixo foram geradas uma vez e ficam congeladas aqui: o teste
 * não depende de rede, de npm nem de Python.
 *
 * Os casos cobrem, de propósito:
 * - os quatro níveis de correção sobre a URL real de uma sala;
 * - a versão 1 (mínima, dominada por preenchimento);
 * - texto com acentuação e travessão (bytes UTF-8 de 2 e 3 octetos);
 * - versões 8 e 9, onde a matriz passa a carregar informação de VERSÃO e onde
 *   a intercalação de blocos de correção deixa de ser trivial.
 *
 * Cada caso valida, junto, sete coisas que só batem se tudo estiver certo:
 * escolha de versão, fluxo de bits, preenchimento, correção Reed-Solomon,
 * intercalação de blocos, zigue-zague de dados, escolha de máscara pela
 * penalidade e gravação dos campos de formato e de versão.
 */


test('localizadores, separadores e temporizadores ficam onde o padrão manda', () => {
  const { modulos, tamanho } = gerarQrCode('https://placar.local/quadra/12345');

  // Os três localizadores são anéis 7×7: borda escura, anel claro, miolo 3×3.
  for (const [linha, coluna] of [
    [0, 0],
    [0, tamanho - 7],
    [tamanho - 7, 0],
  ]) {
    for (let l = 0; l < 7; l++) {
      for (let c = 0; c < 7; c++) {
        const distancia = Math.max(Math.abs(l - 3), Math.abs(c - 3));
        assert.equal(
          modulos[linha + l][coluna + c],
          distancia !== 2,
          `localizador em ${linha},${coluna} no ponto ${l},${c}`
        );
      }
    }
  }

  // Separador: a faixa clara de um módulo em volta de cada localizador.
  for (let i = 0; i < 8; i++) {
    assert.equal(modulos[7][i], false, `separador horizontal superior em ${i}`);
    assert.equal(modulos[i][7], false, `separador vertical esquerdo em ${i}`);
  }

  // Temporizadores: alternância que começa e termina escura.
  for (let i = 8; i < tamanho - 8; i++) {
    assert.equal(modulos[6][i], i % 2 === 0, `temporizador horizontal em ${i}`);
    assert.equal(modulos[i][6], i % 2 === 0, `temporizador vertical em ${i}`);
  }

  // Módulo escuro permanente.
  assert.equal(modulos[tamanho - 8][8], true, 'módulo escuro permanente');
});

test('a quarta borda nunca fica escura: margem clara é responsabilidade do SVG', () => {
  const qr = gerarQrCode('https://placar.local/quadra/12345');
  assert.equal(ladoComMargem(qr.tamanho), qr.tamanho + 8);
  assert.equal(ladoComMargem(qr.tamanho, 0), qr.tamanho);
});

test('caminho SVG tem um retângulo por módulo escuro, deslocado pela margem', () => {
  const qr = gerarQrCode('A', { nivel: 'H' });
  const escuros = qr.modulos.flat().filter(Boolean).length;
  const caminho = caminhoSvg(qr.modulos, 4);
  assert.equal(caminho.split('M').length - 1, escuros, 'um "M" por módulo escuro');
  // O canto superior esquerdo é sempre escuro (localizador) e deve sair na margem.
  assert.ok(caminho.startsWith('M4 4h1v1h-1z'), 'primeiro módulo deslocado pela margem');
  assert.equal(caminhoSvg(qr.modulos, 0).startsWith('M0 0h1v1h-1z'), true);
});

test('bytes UTF-8 são gerados sem depender de TextEncoder', () => {
  assert.deepEqual(paraBytesUtf8('abc'), [0x61, 0x62, 0x63]);
  assert.deepEqual(paraBytesUtf8('ç'), [0xc3, 0xa7]);
  assert.deepEqual(paraBytesUtf8('—'), [0xe2, 0x80, 0x94]);
  assert.deepEqual(paraBytesUtf8('🏐'), [0xf0, 0x9f, 0x8f, 0x90]);
  assert.deepEqual(
    paraBytesUtf8('Vôlei'),
    [...Buffer.from('Vôlei', 'utf8')],
    'mesma saída do Buffer do Node'
  );
});

test('a versão escolhida é a menor que comporta o conteúdo', () => {
  // Nível M na versão 1 comporta 16 códigos de dados: 4 + 8 bits de cabeçalho
  // deixam 14 bytes livres.
  assert.equal(menorVersao(14, 'M'), 1);
  assert.equal(menorVersao(15, 'M'), 2);
  assert.equal(menorVersao(1, 'H'), 1);
  // Versão 10 usa contador de 16 bits: 216 códigos no nível M deixam 213 bytes.
  assert.equal(menorVersao(180, 'M'), 9);
  assert.equal(menorVersao(213, 'M'), 10);
  assert.equal(menorVersao(214, 'M'), null, 'acima da versão 10 devolve nulo');
  assert.equal(menorVersao(271, 'L'), 10, 'teto do codificador: 271 bytes no nível L');
  assert.equal(menorVersao(272, 'L'), null);
});

test('conteúdo impossível falha alto em vez de gerar um QR ilegível', () => {
  assert.throws(() => gerarQrCode(''), /vazio/);
  assert.throws(() => gerarQrCode('oi', { nivel: 'Z' }), /desconhecido/);
  assert.throws(() => gerarQrCode('x'.repeat(2000)), /grande demais/);
});

test('o mesmo conteúdo gera sempre a mesma matriz', () => {
  const a = gerarQrCode('https://placar.local/quadra/12345');
  const b = gerarQrCode('https://placar.local/quadra/12345');
  assert.deepEqual(a.modulos, b.modulos);
  assert.equal(a.mascara, b.mascara);
});
